# Напишіть цикл, який буде вимагати від користувача ввести слово,
# в якому є літера "h" (враховуються як великі так і маленькі).
# Цикл не повинен завершитися, якщо користувач ввів слово без букви "h".

text = ''
while 'h' not in text.lower():
    text = input("1. Введіть якийсь текст з літерою 'h' або 'H': ")

# with regex:

import re
text = ''
while not re.search(r'h', text, re.IGNORECASE):
    text = input("2. Введіть якийсь текст з літерою 'h' або 'H': ")
